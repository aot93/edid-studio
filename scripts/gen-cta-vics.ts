// Generates packages/edid-core/src/data/cta-vics.ts from edid-decode's
// CTA-861 VIC tables (utils/edid-decode/parse-cta-block.cpp in v4l-utils,
// MIT licence). Usage:
//   node scripts/gen-cta-vics.ts <path/to/parse-cta-block.cpp> <commit>

import { readFileSync, writeFileSync } from "node:fs";
import { argv } from "node:process";

const [source, commit] = argv.slice(2);
if (source === undefined || commit === undefined) {
  throw new Error("usage: gen-cta-vics.ts <parse-cta-block.cpp> <commit>");
}
const text = readFileSync(source, "utf8");

function table(name: string): string[][] {
  const start = text.indexOf(`static const struct timings ${name}[] = {`);
  if (start === -1) throw new Error(`${name} not found`);
  const end = text.indexOf("};", start);
  return [...text.slice(start, end).matchAll(/^\s*\{([^}]*)\},/gm)].map((m) =>
    (m[1] ?? "").split(",").map((v) => v.trim()),
  );
}

const rows: string[] = [];
const add = (firstVic: number, entries: string[][]) =>
  entries.forEach((f, i) => {
    // 15 fields, or 18 when borders and even_vtotal follow (VIC 39 only).
    if (f.length !== 15 && f.length !== 18) throw new Error(`VIC ${firstVic + i}: ${f.length} fields`);
    const [hact, vact, hr, vr, clk, rb, il, hfp, hs, hbp, hp, vfp, vs, vbp, vp, hb, vb, even] = f;
    if (rb !== "0") throw new Error(`VIC ${firstVic + i}: unexpected reduced blanking ${rb}`);
    if ((hb ?? "0") !== "0" || (vb ?? "0") !== "0") throw new Error(`VIC ${firstVic + i}: unexpected borders`);
    const b = (v: string | undefined) => (v === "true" ? 1 : 0);
    rows.push(`  [${firstVic + i}, ${hact}, ${vact}, ${hr}, ${vr}, ${clk}, ${b(il)}, ${hfp}, ${hs}, ${hbp}, ${b(hp)}, ${vfp}, ${vs}, ${vbp}, ${b(vp)}, ${b(even)}],`);
  });
add(1, table("edid_cta_modes1"));
add(193, table("edid_cta_modes2"));

writeFileSync(
  new URL("../packages/edid-core/src/data/cta-vics.ts", import.meta.url),
  `// Generated by scripts/gen-cta-vics.ts from edid-decode parse-cta-block.cpp
// (v4l-utils commit ${commit}, MIT licence). Do not edit by hand.
//
// Columns: VIC, h active, v active (frame lines; interlaced fields carry
// half), aspect h, aspect v, pixel clock kHz, interlaced, h front porch,
// h sync, h back porch, h sync positive, v front porch, v sync,
// v back porch (per field when interlaced), v sync positive, even v total
// (VIC 39's 1250-line frame).

export type VicRow = readonly [
  vic: number, hActive: number, vActive: number, aspectH: number, aspectV: number,
  pixelClockKHz: number, interlaced: 0 | 1, hFrontPorch: number, hSync: number, hBackPorch: number,
  hSyncPositive: 0 | 1, vFrontPorch: number, vSync: number, vBackPorch: number, vSyncPositive: 0 | 1,
  evenVTotal: 0 | 1,
];

export const CTA_VIC_ROWS: readonly VicRow[] = [
${rows.join("\n")}
];
`,
);
console.log(`wrote ${rows.length} VICs`);
