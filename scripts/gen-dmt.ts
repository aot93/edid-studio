// Generates packages/edid-core/src/data/dmt.ts from edid-decode's VESA DMT
// table (utils/edid-decode/parse-base-block.cpp in v4l-utils, MIT licence).
// Usage:
//   node scripts/gen-dmt.ts <path/to/parse-base-block.cpp> <commit>

import { readFileSync, writeFileSync } from "node:fs";
import { argv } from "node:process";

const [source, commit] = argv.slice(2);
if (source === undefined || commit === undefined) {
  throw new Error("usage: gen-dmt.ts <parse-base-block.cpp> <commit>");
}
const text = readFileSync(source, "utf8");
const start = text.indexOf("} dmt_timings[] = {");
if (start === -1) throw new Error("dmt_timings not found");
const body = text.slice(start, text.indexOf("\n};", start));

const rows: string[] = [];
// { dmt_id, std_id, cvt_id, { hact, vact, hratio, vratio, pixclk_khz, rb, interlaced,
//   hfp, hsync, hbp, pos_pol_hsync, vfp, vsync, vbp, pos_pol_vsync[, hborder, vborder] } }
for (const m of body.matchAll(/\{\s*(0x[0-9a-f]+),\s*(0x[0-9a-f]+),\s*(0x[0-9a-f]+),\s*\{([^}]*)\}\s*\}/gi)) {
  const f = (m[4] ?? "").split(",").map((v) => v.trim());
  if (f.length !== 15 && f.length !== 17) throw new Error(`DMT ${m[1]}: ${f.length} fields`);
  const [hact, vact, hr, vr, clk, rb, il, hfp, hs, hbp, hp, vfp, vs, vbp, vp, hb, vb] = f;
  const b = (v: string | undefined) => (v === "true" ? 1 : 0);
  rows.push(
    `  [${Number(m[1])}, ${m[2]}, ${hact}, ${vact}, ${hr}, ${vr}, ${clk}, ${rb}, ${b(il)}, ${hfp}, ${hs}, ${hbp}, ${b(hp)}, ${vfp}, ${vs}, ${vbp}, ${b(vp)}, ${hb ?? 0}, ${vb ?? 0}],`,
  );
}
if (rows.length < 80) throw new Error(`only ${rows.length} DMT rows parsed`);

writeFileSync(
  new URL("../packages/edid-core/src/data/dmt.ts", import.meta.url),
  `// Generated by scripts/gen-dmt.ts from edid-decode parse-base-block.cpp
// (v4l-utils commit ${commit}, MIT licence). Do not edit by hand.
//
// Columns: DMT ID, standard timing code (0 when none), h active, v active,
// aspect h, aspect v, pixel clock kHz, reduced blanking (0 none, 1 CVT-RB v1,
// 2 CVT-RB v2), interlaced, h front porch, h sync, h back porch,
// h sync positive, v front porch, v sync, v back porch, v sync positive,
// h border, v border.

export type DmtRow = readonly [
  dmt: number, stdCode: number, hActive: number, vActive: number, aspectH: number, aspectV: number,
  pixelClockKHz: number, rb: number, interlaced: 0 | 1, hFrontPorch: number, hSync: number, hBackPorch: number,
  hSyncPositive: 0 | 1, vFrontPorch: number, vSync: number, vBackPorch: number, vSyncPositive: 0 | 1,
  hBorder: number, vBorder: number,
];

export const DMT_ROWS: readonly DmtRow[] = [
${rows.join("\n")}
];
`,
);
console.log(`wrote ${rows.length} DMT timings`);
